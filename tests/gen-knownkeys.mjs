/* Writes src/core/known-keys.js: every name the application's code reads as a
 * property or quotes as a key. The reading check (readcheck.js) uses it to
 * tell "the app has no use for this key" from "the brief's example does not
 * happen to print it". Re-run after any change to the engine or the renderer:
 *
 *   node tests/gen-knownkeys.mjs
 *
 * readcheck.mjs fails when the file is out of date. */
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './_paths.mjs';

export function harvest() {
  const files = fs.readdirSync(path.join(ROOT, 'src/core')).filter((f) => f.endsWith('.js') && f !== 'known-keys.js')
    .map((f) => path.join(ROOT, 'src/core', f))
    .concat(['render.js', 'index.html', 'docs.js', 'charts.js'].map((f) => path.join(ROOT, f)));
  const set = new Set();
  for (const f of files) {
    const t = fs.readFileSync(f, 'utf8');
    for (const m of t.matchAll(/\.([A-Za-z_]\w{0,39})\b/g)) set.add(m[1].toLowerCase());
    for (const m of t.matchAll(/["'`]([A-Za-z_]\w{0,39})["'`]/g)) set.add(m[1].toLowerCase());
    for (const m of t.matchAll(/\b([A-Za-z_]\w{0,39})\s*:/g)) set.add(m[1].toLowerCase());
  }
  return [...set].sort();
}
export function render(keys) {
  return '/* Generated by tests/gen-knownkeys.mjs. Do not edit by hand. */\n'
    + 'export const KNOWN_KEYS = new Set(' + JSON.stringify(keys) + ');\n';
}
if (process.argv[1] && process.argv[1].endsWith('gen-knownkeys.mjs')) {
  const keys = harvest();
  fs.writeFileSync(path.join(ROOT, 'src/core/known-keys.js'), render(keys));
  console.log(`known-keys.js: ${keys.length} names`);
}
